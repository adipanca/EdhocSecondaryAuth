/*
 * eap_tls_hybrid_bench.c — real end-to-end EAP-TLS Hybrid PQC (RFC 5216 +
 * hybrid-KEM TLS1.3 groups + PQC certs) benchmark harness.
 *
 * Method 6 = "EAP-TLS Hybrid PQC": adapted directly from
 * benchmark/eap_tls_bench.c (method 5, "EAP-TLS Classic") — identical
 * RADIUS/EAP/UDP plumbing, fragmentation, loss emulation, retransmission,
 * CLI contract and CSV schema, so method 6 rows are directly comparable to
 * methods 0..5. What differs from method 5:
 *
 *   - Cryptography: mutual TLS 1.3 using the hybrid KEM group
 *     X25519MLKEM768 (X25519 + ML-KEM-768, the same component algorithms as
 *     method 4's XWING construction) instead of plain X25519, and ML-DSA-44
 *     certificates/signatures instead of RSA-2048.
 *   - Provider: this requires OpenSSL's oqs-provider
 *     (https://github.com/open-quantum-safe/oqs-provider), loaded via the
 *     OPENSSL_CONF / OPENSSL_MODULES env vars (see
 *     benchmark/switch_tls_config.sh and pqc-tls/openssl-hybrid.cnf) —
 *     *not* hard-coded here, so the same binary works whether or not those
 *     env vars are set (falls back to whatever groups/certs are configured,
 *     though without the env vars the ML-DSA-44 cert load will fail).
 *   - Runtime libssl/libcrypto: oqs-provider's TLS1.3 provider-based
 *     signature-algorithm capability (needed for ML-DSA-44 authentication
 *     in the handshake, RFC/PR tracked upstream) is only present in OpenSSL
 *     >= 3.2; the system OpenSSL here is 3.0.13. A private OpenSSL 3.2.6 was
 *     built from source (pqc-tls/openssl32/) purely to supply a newer
 *     libssl.so.3/libcrypto.so.3 at runtime — this binary must be run with
 *     LD_LIBRARY_PATH pointed at pqc-tls/openssl32-install/lib64 (again, see
 *     switch_tls_config.sh), exactly like radiusd is for the hybrid tls-config.
 *   - Certificates: benchmark/certs-pqc/{ca,client}.pem, ML-DSA-44,
 *     generated by this task (see final report for exact commands),
 *     unencrypted private keys (no -key-pass needed).
 *   - Identity: authenticates as "tls-hybrid-ue" (distinct from method 5's
 *     "tls-ue"), purely for clarity in RADIUS/EAP debug logs.
 *   - Verification: after a successful handshake this harness asserts (not
 *     just logs) that the negotiated group is genuinely X25519MLKEM768 via
 *     SSL_get0_group_name() (OpenSSL >= 3.2) — a handshake that silently
 *     fell back to classical x25519 is treated as a FAIL, not a PASS, so a
 *     "successful" run here can never be a silent classical fallback.
 *
 * EAP-TLS message-flight -> CSV column mapping: identical shape/rationale to
 * method 5 (see eap_tls_bench.c's header comment for the full explanation);
 * message_2/message_3 are larger here because they additionally carry the
 * ML-KEM-768 key-share/ciphertext and ML-DSA-44 certs/signatures.
 *
 * This is a benchmark / interoperability harness, not production code.
 */
