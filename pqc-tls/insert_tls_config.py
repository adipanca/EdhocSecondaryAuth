#!/usr/bin/env python3
"""One-shot helper: insert the 'tls-config tls-hybrid-pqc { ... }' block into
the live /usr/local/etc/raddb/mods-available/eap file, right before the
'tls {' (EAP-Type=13 method) block. Idempotent: no-ops if already present."""
import sys

PATH = "/usr/local/etc/raddb/mods-available/eap"
MARKER = "tls-config tls-hybrid-pqc {"
CERTS = "/home/admin-vb/EdhocSecondaryAuth/benchmark/certs-pqc"

BLOCK = f"""\t{MARKER}
\t\t#  Method 6 (EAP-TLS Hybrid PQC) tls-config: ML-DSA-44 mutual certs
\t\t#  (benchmark/certs-pqc/, generated by this task, see final report).
\t\t#  Only used while benchmark/switch_tls_config.sh points the
\t\t#  EAP-Type=13 "tls {{}}" block below at this tls-config instead of
\t\t#  tls-common (classical, method 5). Requires radiusd to be launched
\t\t#  with OPENSSL_CONF/OPENSSL_MODULES env vars set to activate
\t\t#  oqs-provider and offer the hybrid X25519MLKEM768 TLS1.3 group —
\t\t#  see benchmark/switch_tls_config.sh (sets these automatically).
\t\tprivate_key_file = {CERTS}/server.pem
\t\tcertificate_file = {CERTS}/server.pem
\t\tca_file = {CERTS}/ca.pem
\t\t#  @SECLEVEL=0 is required: OpenSSL's generic security-level cert
\t\t#  checks don't recognize PQC signature algorithms (e.g. mldsa44)
\t\t#  and treat them as security-bits=0 ("no shared cipher" / cert
\t\t#  rejected) otherwise. This directive is set explicitly here
\t\t#  because FreeRADIUS calls SSL_CTX_set_cipher_list() with this
\t\t#  exact string, which overrides/resets the process-wide
\t\t#  CipherString default from openssl-hybrid.cnf.
\t\tcipher_list = "DEFAULT:@SECLEVEL=0"
\t\tcipher_server_preference = no
\t\t#  FreeRADIUS defaults ecdh_curve to "prime256v1" and always calls
\t\t#  SSL_CTX_set1_curves_list() with it, which silently resets any
\t\t#  hybrid group set via openssl-hybrid.cnf. Override explicitly --
\t\t#  config-only fix, no FreeRADIUS source patch needed for this part.
\t\tecdh_curve = "X25519MLKEM768:x25519"
\t\t#  FreeRADIUS defaults tls_max_version to TLS 1.2 unless explicitly
\t\t#  set. ML-DSA-44 certs and the hybrid KEM group are both TLS-1.3-only
\t\t#  concepts, so this must be forced to 1.3 or the server negotiates
\t\t#  down to a version where neither exists ("no shared cipher").
\t\ttls_max_version = "1.3"
\t}}

"""

with open(PATH) as f:
    text = f.read()

if MARKER in text:
    print("already present, no-op")
    sys.exit(0)

lines = text.splitlines(keepends=True)
out = []
inserted = False
for ln in lines:
    if not inserted and ln == "\ttls {\n":
        out.append(BLOCK)
        inserted = True
    out.append(ln)

if not inserted:
    print("ERROR: could not find insertion point ('\\ttls {\\n')", file=sys.stderr)
    sys.exit(1)

with open(PATH, "w") as f:
    f.write("".join(out))
print("inserted tls-hybrid-pqc block")
